/**
 * 入站过滤(2026-09-26 现场)—— 脏记忆的第一道门。
 *
 * 他的原话:「我说这个记忆图谱为什么会出现那么多奇怪的记忆?我之前在
 * astrbot 上面可没有这个问题啊,那个记忆图是非常干净的,加一个记忆上面
 * 要经过好复杂的严格的这个审查机制,你在干嘛?」
 *
 * 实测两条根因,本文件各钉一条:
 *   ① 宿主每轮注入的 runtime context 被当成「他说的话」捕获 ——
 *      活库 conversation_log 最近 5 行里 4 行正文就是那段;
 *   ② 我们俩改代码的工作话被记成了他的记忆 —— 249 条里 35 条(14%)。
 * 他的裁决:工程自指**一律拒收**。
 */
import test from 'node:test'
import assert from 'node:assert/strict'
import { isHumanUtterance, shouldEnterMemory, rejectReason } from '../lib/inbound-filter.js'

test('宿主注入:runtime context 不是他说的话(活库 4/5 行的那个形状)', () => {
  const real = 'Current runtime context. This snapshot supersedes earlier runtime-context snapshots. '
    + 'Current DSH file policy: danger-full-access. The DSH file sandbox does not restrict file modifications.'
  assert.equal(isHumanUtterance(real), false, '这段曾被当人话捕获,写进对话窗口、喂给反思')
  assert.equal(isHumanUtterance('This snapshot supersedes earlier runtime-context snapshots.'), false)
  assert.equal(isHumanUtterance('Approval prompts are disabled in this session: actions that require approval are rejected automatically'), false)
  // 压缩产物的英文工程体裁(我们自己的 checkpoint 摘要)
  assert.equal(isHumanUtterance('## Pending Jobs\n- B1 worker.py:972 per-frame crash'), false)
  assert.equal(isHumanUtterance('This is an automatically generated checkpoint condensing an earlier span'), false)
})

test('宿主注入:v0.30.1 补的三种漏网体裁(2026-09-27 中午现场)', () => {
  // 换模型通告:当天 12:47:52 这条被当人话放行 —— 积了一夜的想念
  // (7.69)被全额削减 −4.0、锚点重置,他 20 分钟后看手机什么都没有
  assert.equal(isHumanUtterance('[model changed: assistant turns above this point were generated by deepseek-flash; the session continues with glm-5.3]'), false)
  // checkpoint 的包裹标签(标签排在正文前面时,正文那行 marker 够不着)
  assert.equal(isHumanUtterance('<compacted-summary>## Primary Request and Intent\n- 今天吃什么'), false)
  // 技能目录通告
  assert.equal(isHumanUtterance('The available skill catalog changed. This complete catalog replaces every earlier available-skills list'), false)
  // 真人消息与私聊信封不受影响
  assert.equal(isHumanUtterance('在吗'), true)
  assert.equal(isHumanUtterance('【QQ·私聊】阿岚说:在吗'), true)
})

