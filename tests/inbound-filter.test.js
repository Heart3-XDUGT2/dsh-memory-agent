test('v0.41.0 情绪单轮打分器的提示词不算人话(递归环上缺的那一环)', () => {
  // 事故:打分器每跑一次起一个子代理,而子代理的初始任务经 inbox 投递、
  // 信封写死 source.kind='user' ⇒ 这段提示词在检索取词眼里就是「他这一轮
  // 说的话」。它是当时**唯一**漏过三道判据的内部提示词(开头不是指令式
  // 体裁,长度又够)。这里用真提示词逐字回归(模板在 emotion-score.js)。
  const real = '你只做一件事:读下面这句话之后,Echo 的情绪**变成什么样**。\n'
    + '不要解释、不要安慰、不要写对话 —— 只给数字。\n\n'
    + '【现在的情绪(零点)】\n- 疲惫 2/10 · 心情 5 · 唤醒度 3/10\n\n'
    + '【他刚说的这句】\n阿岚,我今天好累\n\n'
    + '【怎么改】\n- 数字都是 0~10。**没被这句话碰到的那几维,原样返回,不要动。**'
  assert.equal(isHumanUtterance(real), false)
  // rejectReason 的第一道闸就是 isHumanUtterance(内部提示词在它里面已经被拒),
  // 所以理由落成 'host-injection' —— 与其它内部提示词同一个理由,不再是漏网。
  assert.equal(rejectReason(real).reason, 'host-injection')
  // 闸不许误伤:他自己的话照旧放行(「你只做…」不是他打字的开头体裁)
  assert.equal(isHumanUtterance('你今天怎么这么晚才回我'), true)
  assert.equal(isHumanUtterance('我今天好累'), true)
})
