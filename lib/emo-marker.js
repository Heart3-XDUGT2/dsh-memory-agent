/**
 * `<emo>` / `<skip>` 语气标签的**文字渠道剥离**(2026-10-05 拍板 1/2;
 * 2026-10-07 语法由方括号点标记改为 XML 标签)。
 *
 * 背景:为什么这里要剥一次
 * ----------------------
 * `<emo type="2">…</emo>` 与 `<skip>…</skip>` 是 **heart-tts**(语音输出插件)
 * 的行内语气标签:它订阅 `agent/assistant-stream` 拿**原始文本**、按标签范围挑
 * 语气,并在 TTS 层把标签剥掉。所以**她念出来的声音是干净的**。
 * 但**文字渠道**没人剥 ⇒ DSH 界面、QQ、对话记录/漂移/反思输入都带着这串机器语法。
 *
 * 为什么不"在上游统一剥"
 * ----------------------
 * 宿主里唯一能改写助手文本、并同时影响"落盘 + 界面"的钩子是 host 侧
 * `llm/stream`(cordis waterfall)。而 heart-tts 读的正是同一条流的派发事件
 * `agent/assistant-stream` —— **在上游剥会把它的标签一起剥掉,按句语气功能直接死**。
 * ⇒ 他 2026-10-05 拍板(拍板 1/2):**两个消费者各自剥,互不干扰**;
 * 这个模块负责"文字渠道"那一半,语音那一半仍在 heart-tts 里。
 *
 * 语法契约(2026-10-07 换语法,与 heart-tts 逐字对齐)
 * ------------------------------------------------
 *     <emo type="2">这句话用 2 号样式读。</emo>
 *     <emo type='强调·上扬'>…</emo>
 *     <skip>这段不要读出来。</skip>
 *
 *   · `type` 对 `<emo>` **必填**;半角单引号与双引号都认,属性值前后可有空格。
 *   · `<emo>` 只丢**标签本身**,正文留下(`type` 值在这里没有用途,剥掉就走)。
 *   · `<skip>` 连**正文一起**丢掉 —— 那是给语音的"别读",文字渠道同样不该显示
 *     (它本来就是"不该被看到"的内容)。
 *
 * 为什么换语法(2026-10-07)
 * ------------------------
 * 旧的 `[emo:N]` 是**点标记**:它落在哪一句,取决于"句子边界在哪",而边界是
 * heart-tts 的句子缓冲区按 `min_chars` 裁出来的 —— 短句会被合并成一条,于是
 * 一个写在句尾的标记究竟管哪一句,变成**依赖缓冲状态**的推断,出现过"该跳过的
 * 那句照读不误"。XML 标签把范围写死在文本里,**根本不依赖句子怎么切**;
 * 两种标签也不会互相嵌套/重合(不配对就是畸形,按下面的口径原样保留)。
 *
 * 剥什么(拍板 1,不变)
 * ------------------
 * **只剥标签本身**。emoji、代码块、链接、行标记、'#' 一律不动 ——
 * 那是 heart-tts 为"念出来"做的清洗,不是给人的;文字渠道不该丢这些。
 *
 * 刻意不做的事(取舍照旧,理由是现场换来的)
 * ------------------------------------
 *   - **不做代码块/行内代码感知**:这是控制语法,出现在代码块里的概率≈0;
 *     真出现也照剥(与 heart-tts 的处理一致)。拍板 1 的"不动代码块"指的是
 *     "不要顺手把代码块、链接、emoji 一起清了"。
 *   - **不处理"没写完"的标签**:`<emo type="2`、`<em`、`<emo` 这类**没有 `>`
 *     收尾**的片段一律**原样保留** —— 它可能只是正文里的一个小于号
 *     (「数学 a < b」),宁可漏剥,也不误删正文。**形状完整的标签则一律剥掉**,
 *     哪怕它的 `type` 缺了或写歪了:`type` 是否合法是 heart-tts 那边的契约,
 *     这一侧的职责只是"机器语法不显示给他看"。
 *   - **未闭合的 `<skip>` 例外**:按「到文本末尾」处理。这不是"误删正文" ——
 *     被 `<skip>` 标住的内容本来就明说了不该显示,而**留着一个 `<skip>` 在
 *     界面上等于直接违反"标签绝不显示"这条硬约束**。两害相权取其轻:
 *     少显示一段该藏的话,好过把机器语法端到他眼前。
 *   - **不做 delta 状态机**:主包这一侧拿到的是**整条 assistant 消息**
 *     (`lib/index.js:2501` 的 `textOf(msg)`),不是流式片段。heart-tts 那边要
 *     状态机是因为它吃的是逐 delta 的流(标签可能横跨两个 delta)。
 */

/**
 * `<emo …>` 开标签。**只认形状,不校验 `type`**。
 *
 * 为什么不像 heart-tts 那样要求 `type` 必填:那一侧要 `type` 是因为它得**用**
 * 这个值挑语气;这一侧只负责"别把机器语法显示给他看",值的合法性与我们无关。
 * 更要紧的是,**要求 `type` 会造出"剥了一半"的状态** —— `<emo>缺 type</emo>`
 * 变成开标签留着、闭标签被剥掉,半截标签比两种极端都难看。所以:形状像标签就整个剥掉,
 * 形状不完整(没有 `>`)才原样保留。`type` 必填是模型那边的契约,不是这里的判据。
 */
const EMO_OPEN_G = /<emo\b[^>]*>/gi

/** `</emo>`(闭标签允许 `</emo >` 这种内侧空格)。 */
const EMO_CLOSE_G = /<\/emo\s*>/gi

/** `<skip>…</skip>` 整对,**连正文**一起吃掉。 */
const SKIP_PAIR_G = /<skip\s*>[\s\S]*?<\/skip\s*>/gi

/** 未闭合的 `<skip>`:按「到文本末尾」处理(理由见文件头"刻意不做的事")。 */
const SKIP_TAIL_G = /<skip\s*>[\s\S]*$/i

/**
 * 剥掉文字渠道不该出现的语气标签。
 * @param {unknown} text
 * @returns {string} 剥完的文本(非字符串输入 ⇒ 空串;空输入 ⇒ 空串)
 */
export function stripEmoMarkers (text) {
  const s = typeof text === 'string'
    ? text
    : (text === null || text === undefined ? '' : String(text))
  if (s === '') return ''
  return s
    // ① skip 先走:它的正文是要**丢掉**的,不能留给后面任何一步。
    //    (先配整对、再配未闭合的尾巴 —— 顺序反了会把整段正文一起吞掉。)
    .replace(SKIP_PAIR_G, '')
    .replace(SKIP_TAIL_G, '')
    // ② emo:只丢标签,正文留下。
    .replace(EMO_OPEN_G, '')
    .replace(EMO_CLOSE_G, '')
}

/**
 * 有没有语气标签(诊断用,**不动文本**)。
 *
 * 实现就是"剥一次看变没变":判据与 `stripEmoMarkers` **天然一致**(不会出现
 * "判有但剥不掉"),而且不必再手动复位正则的 `lastIndex` —— 旧实现在这点上
 * 要复位两次,是个随时会飘的坑。
 *
 * @param {unknown} text
 * @returns {boolean}
 */
export function hasEmoMarker (text) {
  const s = typeof text === 'string' ? text : ''
  if (s === '') return false
  return stripEmoMarkers(s) !== s
}
